// Path classes used by rules, risk scoring and exclusions (doc 05 §6 generated code; doc 06 plat-01 "not a substring test on test").
const GENERATED_PATH = /(^|\/)(generated|__generated__|\.generated)(\/|$)|\.(gen|generated)\.[cm]?[jt]sx?$|\.graphql\.ts$|(^|\/)prisma\/client(\/|$)|\.pb\.ts$/;
const GENERATED_MARKER = /@generated|DO NOT EDIT|auto-?generated|generated by|this file was (auto)?generated/i;
const TEST_FILE = /\.(test|spec|e2e|cy|stories|story)\.[cm]?[jt]sx?$/;
const TEST_DIR = /(^|\/)(__tests__|__mocks__|__fixtures__|tests?|e2e|cypress|playwright|fixtures?|mocks?|stories|\.storybook)(\/|$)/;
const CONFIG_FILE = /(^|\/)[^/]*\.(config|conf|setup|rc)\.[cm]?[jt]s$|(^|\/)(vite|vitest|jest|webpack|rollup|esbuild|tsup|tsdown|playwright|cypress|eslint|babel|next|nuxt|svelte|astro|tailwind|postcss|drizzle|prisma|knip|wrangler)[^/]*\.[cm]?[jt]s$/;
const SCRIPT_DIR = /(^|\/)(scripts?|tools?|build|bin|ci|\.github|\.husky)(\/|$)/;

export const isGeneratedPath = (p) => GENERATED_PATH.test(p);
export const hasGeneratedMarker = (headText) => GENERATED_MARKER.test(headText);
export const isTestPath = (p) => TEST_FILE.test(p) || TEST_DIR.test(p);
export const isConfigPath = (p) => CONFIG_FILE.test(p);
export const isScriptPath = (p) => SCRIPT_DIR.test(p);
export const pathClass = (p) => (isGeneratedPath(p) ? 'generated' : isTestPath(p) ? 'test' : isConfigPath(p) ? 'config' : isScriptPath(p) ? 'script' : 'source');

export const SOURCE_EXT = /\.(?:[cm]?[jt]sx?|vue|svelte|astro)$/;
export const TS_EXT = /\.(?:[cm]?tsx?|vue|svelte|astro)$/;
export const SFC_EXT = /\.(?:vue|svelte|astro)$/;

/** nearest enclosing package path for a repo-relative file */
export function packageOf(file, packages) {
  let best = '.';
  let bestLen = -1;
  for (const p of packages) {
    if (p.path === '.') { if (bestLen < 0) { best = '.'; bestLen = 0; } continue; }
    if ((file === p.path || file.startsWith(p.path + '/')) && p.path.length > bestLen) { best = p.path; bestLen = p.path.length; }
  }
  return best;
}
