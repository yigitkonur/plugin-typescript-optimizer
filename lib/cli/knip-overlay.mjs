// ts-opt knip-overlay [--write] [--from-verdicts]: the minimal Knip config that encodes proven false positives, kept in
// .ts-optimize/knip.config.jsonc — the user's own Knip config is never edited (doc 06 §12.2).
import { join } from 'node:path';
import { readVerdicts } from '../artifacts/candidates.mjs';
import { ART, resolveRunId } from '../artifacts/store.mjs';
import { EXIT, TsOptError } from '../core/envelope.mjs';
import { isFile, readJsonc, writeAtomic } from '../core/fs.mjs';
import { detect } from '../detect/index.mjs';
import { findRoot } from '../detect/root.mjs';

export const spec = { write: 'boolean', 'from-verdicts': 'boolean' };
const KEYS = ['entry', 'project', 'ignore', 'ignoreDependencies', 'ignoreBinaries', 'ignoreExportsUsedInFile'];

/** `knip: entry lib/widgets/*.ts` / `knip entry=…` / `knip: ignoreDependencies postcss` -> {key, value} */
export function parseCodify(s) {
  const m = /knip[:\s]+(entry|project|ignoreDependencies|ignoreBinaries|ignoreExportsUsedInFile|ignore)\b\s*[:=]?\s*(.+)$/i.exec(String(s || '').trim());
  if (!m) return null;
  const key = KEYS.find((k) => k.toLowerCase() === m[1].toLowerCase());
  const value = m[2].trim().replace(/^["'`]|["'`.]+$/g, '');
  return key && value ? { key, value } : null;
}

export async function run({ cwd, flags }) {
  const { root } = await findRoot(cwd);
  const d = await detect(root);
  if (!d.typescript) throw new TsOptError(EXIT.NOTHING, `No TypeScript found under ${d.root}; nothing to do.`);
  const file = join(root, ART, 'knip.config.jsonc');
  const prev = isFile(file) ? readJsonc(file).value || {} : {};
  const ov = { entry: [...(prev.entry || [])], project: [...(prev.project || [])], ignore: [...(prev.ignore || [])], ignoreDependencies: [...(prev.ignoreDependencies || [])], ignoreBinaries: [...(prev.ignoreBinaries || [])], ...(prev.ignoreExportsUsedInFile ? { ignoreExportsUsedInFile: prev.ignoreExportsUsedInFile } : {}) };
  const sources = [];
  const add = (key, value, why) => { if (!ov[key]) ov[key] = []; if (!ov[key].includes(value)) { ov[key].push(value); sources.push(`${key}: ${value} (${why})`); } };

  // bootstrap, from detection alone
  const wk = d.packs.find((p) => p.name === 'workerd');
  for (const v of wk?.variants || []) {
    for (const c of v.rpc_classes || []) if (c.file) add('entry', c.file, `${c.kind} ${c.class_name} registered in ${v.wrangler_file}`);
    for (const a of v.ambient_files || []) add('ignore', a, 'import-less ambient declarations');
  }
  // Framework entries and config-referenced packages are NOT added at bootstrap: Knip's own plugins cover them. They enter the
  // overlay only when a triager proved a plugin missed one (--from-verdicts), keeping the overlay minimal.

  // refinement, from the triagers' --codify entries
  let unparsed = 0;
  if (flags['from-verdicts']) {
    const id = resolveRunId(root, flags.run);
    for (const v of readVerdicts(root, id)) {
      if (!v.codify) continue;
      const p = parseCodify(v.codify);
      if (!p) { unparsed++; continue; }
      if (p.key === 'ignore' && !/\.d\.[cm]?ts$/.test(p.value)) { sources.push(`ignore: ${p.value} REFUSED (only a single import-less ambient .d.ts may be ignored; use entry/project instead)`); continue; }
      add(p.key, p.value, `triage verdict ${v.candidate}`);
    }
  }
  const out = { $schema: 'https://unpkg.com/knip@6/schema.json', ...Object.fromEntries(Object.entries(ov).filter(([, v]) => (Array.isArray(v) ? v.length : v))) };
  const text = `// Generated by ts-opt knip-overlay. Used via \`knip --config\` only when the project has no Knip config of its own.\n// Copy to knip.jsonc to promote it; the plugin never edits your configuration.\n${JSON.stringify(out, null, 2)}\n`;
  if (flags.write) writeAtomic(file, text);
  return { result: { path: `${ART}/knip.config.jsonc`, written: !!flags.write, overlay: out, sources, unparsed_codify: unparsed }, text: `${flags.write ? 'wrote' : 'would write'} ${ART}/knip.config.jsonc\n${sources.join('\n') || '(nothing proven needed)'}${unparsed ? `\n${unparsed} --codify entries were not in the "knip: <key> <value>" form and were ignored` : ''}` };
}
